# Determine if a fruit is ripe, overripe, or unripe based on its color. (e.g., Banana: Green - Unripe, Yellow - Ripe, Brown - Overripe)

Color = str(input("Color of banana: "))

if Color == "Green":
    print("Unripe")
       
elif Color == "Yellow":
    print("Ripe")
       
elif Color == "Brown":
    print("Overripe")
       
