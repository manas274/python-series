# Problem: Suggest an activity based on the weather 
# (e.g., Sunny - Go for a walk, Rainy - Read a book, Snowy - Build a snowman).

Weather = str(input("How is the weather: "))

if Weather == "Sunny":
    print("Go for a walk")
    
elif Weather == "Rainy":
    print("Read a book")
    
elif Weather == "Snowy":
    print("Build a snowman")
